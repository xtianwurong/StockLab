-- ==============================================================================
-- StockLab 迁移 007：大宗商品价格序列（石油 / 猪肉 / 黄金 … 择时参考）
-- ==============================================================================
-- 设计前提（与 stocklab/domain/commodity.py 的模块说明一一对应）：
--
--   1. 只存一张价格表，不存品种登记表。
--      品种登记（名称 / 分类 / 计价单位 / 抓哪个合约）写在
--      stocklab/datasource/commodity/registry.py 里，因为那一半内容本质是
--      **抓取策略**（哪个 akshare 接口、哪个合约代码），它属于代码而不是数据：
--      拆进表里就得先写一步 `load-sources`，而且会出现「代码里改了、表里没改」
--      的静默分叉。品种元信息不会被业务系统并发修改，没有落库的收益。
--
--   2. 主键 (symbol, trade_date) + UPSERT，而不是只 INSERT。
--      价格与语录不同：语录是既成事实，改原文会破坏审计链；价格是可修正的
--      观测值 —— 抓取当天可能拿到一根被污染的行（源站补数据、合约换月回填），
--      下一轮同步必须能覆盖它。所以这里用 upsert，fetched_at 随之刷新，
--      表里能看到「这条是哪一轮同步写进来的」。
--
--   3. close 允许为任意正数，不设 CHECK 约束。
--      各品种计价单位不同（元/吨、元/克、元/桶），量纲差三个数量级，
--      数据库层加范围约束必然误伤；契约校验放在归一化层（datasource）做，
--      那里知道每个品种的合理区间。
--
--   4. 不存 raw_meta / 原始 OHLCV。
--      本页只回答「当前价格在过去几年里算贵还是算便宜」，收盘价一个字段够了。
--      存整根 K 线等于把 akshare 的返回结构固化进表结构，源站一改列名就得迁移。
-- ==============================================================================

CREATE SCHEMA IF NOT EXISTS commodity;

-- ---------------------------------------------------------------------------
-- 大宗商品收盘价序列
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS commodity.price_history (
    symbol      VARCHAR   NOT NULL,
    trade_date  DATE      NOT NULL,
    close       DOUBLE    NOT NULL,
    source      VARCHAR   NOT NULL,
    fetched_at  TIMESTAMP NOT NULL,
    PRIMARY KEY (symbol, trade_date)
);
